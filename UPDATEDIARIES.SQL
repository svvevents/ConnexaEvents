DELIMITER $$
CREATE DEFINER=`root`@`localhost` PROCEDURE `UpdateDiaries`(IN 
buyerID INT, 
supplierID INT,
AppointmentNum VARCHAR(50),
AppointmentType VARCHAR(25)
)
BEGIN

	/*SET BUYER AND APPOINTMENT NUMBER*/
	UPDATE SUPPLIER_MEETINGS
	SET STATUS = 'MEETING BOOKED'
	, BUYER_ID = buyerID
	, MEETING_TYPE = AppointmentType
	WHERE SUPPLIER_ID = supplierID
		AND APPOINTMENT = AppointmentNum;
    
    /*SET ADDITIONAL BUYER'S INFO*/
	UPDATE SUPPLIER_MEETINGS SM 
		JOIN buyer_attendees BA ON SM.BUYER_ID = BA.attendee_id
	SET SM.TABLE_NUMBER = BA.TABLEALLOCATED
	, SM.BUYER_FULLNAME = BA.FULLNAME
	, SM.BUYER_ORG = BA.ORGANIZATION
	WHERE SM.SUPPLIER_ID = supplierID
	AND SM.APPOINTMENT = AppointmentNum;


	/*SET SUPPLIER_ID AND APPOINTMENT NUMBER TO THE BUYER'S DIARY*/
	UPDATE BUYER_MEETINGS BM
	SET STATUS = 'MEETING BOOKED'
	, BM.SUPPLIER_ID = supplierID
	, BM.MEETING_TYPE = AppointmentType
	WHERE BM.BUYER_ID = buyerID
		AND BM.APPOINTMENT = AppointmentNum;
        
	UPDATE BUYER_MEETINGS BM 
		JOIN SUPPLIER_ATTENDEES SA ON BM.SUPPLIER_ID = SA.attendee_ID
	SET BM.SUPPLIER_FULLNAME = SA.FULLNAME
	, BM.SUPPLIER_ORG = SA.ORGANIZATION
	WHERE bm.BUYER_ID = buyerID
		AND bm.APPOINTMENT = AppointmentNum;

END$$
DELIMITER ;
